import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,writeFileSync,readFileSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {ExperimentStore} from '../server/experiments.js';

test('legacy histories keep identities across restart and custom code is never grouped by display name',()=>{
  const directory=mkdtempSync(join(tmpdir(),'distvis-experiment-migration-'));
  let store=new ExperimentStore(directory);
  const oldSource={source:'package main\nfunc main() {}\n',nodeSources:{'node-2':'package main\nfunc main() { println("override") }\n'}};
  const run=(id,protocol)=>({id,config:{name:'Same display name',protocol,runtime:'docker',nodeCount:3},createdAt:'2026-09-19T00:00:00.000Z'});
  const a=run('old-a','custom'),b=run('old-b','custom');
  store.adopt(a,oldSource);store.adopt(b,oldSource);
  assert.notEqual(a.config.experimentId,b.config.experimentId);
  assert.ok(store.getProtocol(store.get(a.config.experimentId).protocolId).projects['node-2']);
  const raft1=run('raft-1','raft'),raft2=run('raft-2','raft');
  store.adopt(raft1,oldSource);store.adopt(raft2,oldSource);
  assert.equal(raft1.config.experimentId,raft2.config.experimentId,'known historical example gets one compatibility group');
  const directory1=run('dir-1','directory:lesson'),directory2=run('dir-2','directory:lesson');
  directory1.config.project={root:'/first'};directory2.config.project={root:'/second'};
  store.adopt(directory1,oldSource);store.adopt(directory2,oldSource);
  assert.notEqual(directory1.config.experimentId,directory2.config.experimentId,'same folder name in different roots is independent');
  store=new ExperimentStore(directory);
  assert.equal(store.adopt(a,oldSource),false,'migration is idempotent');
  assert.equal(store.items.size,5);
  assert.match(Buffer.from(store.getProtocol(store.get(a.config.experimentId).protocolId).projects['node-2'].files.find(f=>f.path==='main.go').content,'base64').toString(),/override/);
});

test('workspace migration shares only identical code and keeps child settings and IDs',()=>{
  const dir=mkdtempSync(join(tmpdir(),'distvis-hierarchy-'));mkdirSync(join(dir,'experiments'));
  const project={entry:'.',files:[{path:'main.go',content:'package main\nfunc main(){}\n'},{path:'cmd/node/main.go',content:'package main\nfunc main(){}\n'},{path:'go.mod',content:'module lesson/test\n\ngo 1.24\n'}]};
  const original=new ExperimentStore(mkdtempSync(join(tmpdir(),'distvis-seed-')));
  const normalized=original.createProtocol({name:'Same code',projects:{shared:project}}).projects;
  const item={name:'Existing',protocol:'custom',projects:normalized,settings:{runtime:'docker',nodeCount:3,seed:42,latency:80,bandwidth:128},revision:4};
  for(const id of ['a','b'])writeFileSync(join(dir,'experiments',id+'.json'),JSON.stringify({...item,id,settings:{...item.settings,latency:id==='a'?80:800}}));
  const different=structuredClone(item);different.projects.shared=original.createProtocol({name:'Different',projects:{shared:{...project,files:project.files.map(f=>({...f,content:f.content+(f.path==='main.go'?'// different\n':'')}))}}}).projects.shared;
  writeFileSync(join(dir,'experiments','c.json'),JSON.stringify({...different,id:'c'}));
  const otherEntry=structuredClone(item);otherEntry.projects.shared.entry='./cmd/node';
  writeFileSync(join(dir,'experiments','d.json'),JSON.stringify({...otherEntry,id:'d'}));
  let store=new ExperimentStore(dir);
  assert.equal(store.get('a').protocolId,store.get('b').protocolId);
  assert.notEqual(store.get('a').protocolId,store.get('c').protocolId);
  assert.notEqual(store.get('a').protocolId,store.get('d').protocolId,'different build entries remain separate protocols');
  assert.equal(store.get('b').settings.latency,800);assert.equal(store.get('a').revision,4);
  assert.equal(JSON.parse(readFileSync(join(dir,'experiments','a.json'),'utf8')).projects,undefined);
  store=new ExperimentStore(dir);assert.equal(store.protocolItems.size,3);assert.equal(store.items.size,4);
});

test('explicit merges preserve experiments, old links and code variants; archives survive restart',()=>{
  const dir=mkdtempSync(join(tmpdir(),'distvis-organize-'));
  let store=new ExperimentStore(dir);
  const project={entry:'.',files:[{path:'main.go',content:'package main\nfunc main(){}\n'},{path:'go.mod',content:'module lesson/test\n\ngo 1.24\n'}]};
  const a=store.createProtocol({name:'Token',projects:{shared:project}});
  const b=store.createProtocol({name:'Token',projects:{shared:project},origin:{root:'/original'}});
  const child=store.create({name:'slow',protocolId:b.id,settings:{latency:400},archived:true});
  const run={id:'record',config:{experimentId:child.id,protocolId:b.id},createdAt:'2026-09-19',status:'completed'};
  const originalRun=JSON.stringify(run);
  store.mergeProtocol(b.id,a.id);
  assert.equal(store.get(child.id).protocolId,a.id);
  assert.equal(store.get(child.id).settings.latency,400);
  assert.equal(store.get(child.id).origin.root,'/original');
  assert.equal(store.getProtocol(b.id).id,a.id);
  assert.equal(store.listProtocols(new Map([[run.id,run]]))[0].runCount,1);
  assert.equal(JSON.stringify(run),originalRun);
  const variant=store.createProtocol({name:'Token',projects:{shared:project,'node-2':project}});
  assert.throws(()=>store.mergeProtocol(variant.id,a.id),/不能合并/);
  const independent=store.createProtocol({name:'Token',projects:{shared:project}});
  store.saveProtocol(variant.id,{revision:variant.revision,archived:true});
  store=new ExperimentStore(dir);
  assert.equal(store.getProtocol(b.id).id,a.id);
  assert.equal(store.get(child.id).archived,true);
  assert.equal(store.getProtocol(variant.id).archived,true);
  assert.equal(store.getProtocol(independent.id).id,independent.id,'identical user-created projects are never automatically merged');
  assert.equal(store.listProtocols(new Map()).length,3);
  const archived=store.getProtocol(variant.id);
  store.saveProtocol(variant.id,{revision:archived.revision,archived:false});
  assert.equal(store.getProtocol(variant.id).archived,false);
});
